// Regenerate crates/mdust/src/tables.rs. Run from bench/: node ../tools/gen_tables.cjs <entities.rs>
const fs = require('fs');
const path = require('path');
const { decodeHTMLStrict } = require(require.resolve('entities', {paths: [process.cwd()]}));
const md = require(require.resolve('markdown-it', {paths: [process.cwd()]}));
const utils = new md().utils;

const src = fs.readFileSync(process.argv[2], 'utf8');
const names = new Set();
for (const m of src.matchAll(/entity: "&([A-Za-z0-9]+);"/g)) names.add(m[1]);
const entries = [];
for (const n of names) {
  const d = decodeHTMLStrict('&' + n + ';');
  if (d !== '&' + n + ';') entries.push([n, d]);
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

let blob = '';
const offs = [];
for (const [n, d] of entries) {
  offs.push([Buffer.byteLength(blob), n.length, Buffer.byteLength(d)]);
  blob += n + d;
}

const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x110000; cp++) {
  const p = cp < 0x110000 && (cp < 0xd800 || cp > 0xdfff) && utils.isPunctCharCode(cp);
  if (p && start < 0) start = cp;
  if (!p && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
let out = '// Generated by tools/gen_tables.cjs. Do not edit.\n\n';
out += `pub static ENTITY_BLOB: &str = "${esc(blob)}";\n\n`;
out += '// (blob offset, name len, value len), sorted by name.\n';
out += `pub static ENTITY_INDEX: [(u16, u8, u8); ${offs.length}] = [\n`;
for (const o of offs) out += `    (${o[0]}, ${o[1]}, ${o[2]}),\n`;
out += '];\n\n';
out += `pub static PUNCT_RANGES: [(u32, u32); ${ranges.length}] = [\n`;
for (const r of ranges) out += `    (0x${r[0].toString(16)}, 0x${r[1].toString(16)}),\n`;
out += '];\n';
fs.writeFileSync(path.join(__dirname, '../crates/mdust/src/tables.rs'), out);
console.log('entities', entries.length, 'blob', Buffer.byteLength(blob), 'punct ranges', ranges.length);
